"""Single-source integration identity and fail-closed package checks."""
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CONTRACT = json.loads((HERE / 'integration-contract.json').read_text())
SWIFT = ROOT / 'ImageAll/Application/Story/OpenMontageContract.swift'

def swift_source():
    fields = ('taskProtocolVersion', 'taskProtocolSHA256', 'storySchemaVersion', 'storySchemaSHA256',
              'creativeProtocolVersion', 'creativePluginVersion', 'templateProtocolVersion',
              'legacyStorySchemaVersion', 'legacyStorySchemaSHA256')
    return '// Generated by scripts/openmontage/integration_contract.py; edit integration-contract.json.\n' + 'enum OpenMontageContract {\n' + ''.join(f'    static let {k} = "{CONTRACT[k]}"\n' for k in fields) + '}\n'

def validate(engine, check_swift=True):
    if check_swift and SWIFT.read_text() != swift_source():
        raise RuntimeError('Generated Swift contract is stale; run integration_contract.py --generate')
    directory = engine / 'schemas/integrations'
    for name, key in [('story_render_package_v0_1', 'legacyStorySchemaSHA256'), ('story_render_package_v0_2', 'storySchemaSHA256'), ('story_executor_task_protocol_v1', 'taskProtocolSHA256')]:
        data = (directory / (name+'.schema.json')).read_bytes()
        lock = json.loads((directory / (name+'.lock.json')).read_text())
        if hashlib.sha256(data).hexdigest() != CONTRACT[key] or lock['sha256'] != CONTRACT[key]:
            raise RuntimeError('Integration schema/lock mismatch: '+name)
    schema = json.loads((directory/'story_executor_task_protocol_v1.schema.json').read_text())
    expected_pairs = {(CONTRACT['legacyStorySchemaVersion'], CONTRACT['legacyStorySchemaSHA256']),
                      (CONTRACT['storySchemaVersion'], CONTRACT['storySchemaSHA256'])}
    for name in ('task','completion'):
        choices = schema['$defs'][name]['properties']['storyPackage']['oneOf']
        pairs = {(c['properties']['schemaVersion']['const'], c['properties']['schemaSHA256']['const']) for c in choices}
        if pairs != expected_pairs:
            raise RuntimeError('Envelope story identity mismatch')
    creative = (engine/'lib/story_auto_creative.py').read_text()
    version = re.search(r"^VERSION = ['\"]([^'\"]+)", creative, re.M)
    if not version or version[1] != CONTRACT['creativePluginVersion']:
        raise RuntimeError('Creative plugin contract mismatch')
    return CONTRACT

if __name__ == '__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--generate',action='store_true');p.add_argument('--engine',type=Path)
    a=p.parse_args()
    if a.generate: SWIFT.write_text(swift_source())
    if a.engine: validate(a.engine);print('Integration contract verified')
