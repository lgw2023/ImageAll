#!/usr/bin/env python3
"""Create NEW synthetic cold-recovery state; never accept an existing data root."""
import hashlib
import json
import pathlib
import sys
import uuid

root = pathlib.Path(sys.argv[1])
non_sparse = "--non-sparse" in sys.argv[2:]
large_mib = int(sys.argv[sys.argv.index("--large-mib") + 1]) if "--large-mib" in sys.argv else 4096
remaining_mib = int(sys.argv[sys.argv.index("--remaining-mib") + 1]) if "--remaining-mib" in sys.argv else 8
if remaining_mib not in [8, 32] or remaining_mib >= large_mib:
    raise SystemExit("remaining-mib must be 8 or 32 and smaller than large-mib")
if large_mib < 16 or large_mib % 4:
    raise SystemExit("large-mib must be at least 16 and a multiple of 4")
if root.is_symlink() or str(root.resolve()).startswith('/Volumes/HDD2'):
    raise SystemExit('protected or linked root rejected')
root.mkdir(parents=True, exist_ok=False)
(root / 'SYNTHETIC-ONLY').write_text('Generated transfer bytes, no user media.\n')
source = root / 'source'
source.mkdir()
(root / 'sender').mkdir()
migration, device, install = (str(uuid.uuid4()) for _ in range(3))
package = root / 'receiver' / ('.imageall-transfer-' + migration) / 'package'
(package / 'resources').mkdir(parents=True)
chunk_size = 4 * 1024**2
large_size = large_mib * 1024**2
remaining_chunks = remaining_mib // 4
prefix_size = large_size - remaining_chunks * chunk_size
chunks, receipts, resources = {}, {}, []
small_bytes = 0
for index in range(2889):
    resource_id = str(uuid.uuid4())
    rel = 'resources/' + resource_id + '.bin'
    is_large = index == 2888
    if is_large:
        zero = bytes([37 if non_sparse else 0]) * chunk_size
        suffix = bytes([73]) * chunk_size
        digest = hashlib.sha256()
        for _ in range(prefix_size // chunk_size):
            digest.update(zero)
        for _ in range(remaining_chunks): digest.update(suffix)
        sha = digest.hexdigest()
        size = large_size
        with (source / 'pending.bin').open('wb') as f:
            if non_sparse:
                for _ in range(prefix_size // chunk_size):
                    f.write(zero)
            else:
                f.truncate(prefix_size)
            f.seek(prefix_size)
            for _ in range(remaining_chunks): f.write(suffix)
        with (package / rel).open('wb') as f:
            if non_sparse:
                for _ in range(prefix_size // chunk_size):
                    f.write(zero)
            else:
                f.truncate(prefix_size)
            f.seek(prefix_size)
            f.write(b'uncommitted-tail')
        chunk_hash = hashlib.sha256(zero).hexdigest()
        chunks[rel] = [dict(offset=i, byteCount=chunk_size, sha256=chunk_hash)
                       for i in range(0, prefix_size, chunk_size)]
    else:
        # Mixed sizes; deterministic generated bytes, not media-decoder fixtures.
        size = [4096, 32768, 131072][index % 3]
        data = bytes([index % 251]) * size
        sha = hashlib.sha256(data).hexdigest()
        (package / rel).write_bytes(data)
        chunks[rel] = [dict(offset=0, byteCount=size, sha256=sha)]
        receipts[rel] = dict(migrationID=migration, deviceID=device,
                            resource=dict(relativePath=rel, byteCount=size, sha256=sha))
        small_bytes += size
    resources.append(dict(id=resource_id, role='original', version=1,
                          uniformTypeIdentifier='public.data', required=True,
                          status='present', relativePath=rel, byteCount=size, sha256=sha))
session = dict(formatVersion=1, migrationID=migration, deviceID=device,
               sourceInstallID=install, chunksByPath=chunks, sealed=False,
               verifiedResources=receipts)
(package.parent / 'session.json').write_text(json.dumps(session))
(root / 'scenario.json').write_text(json.dumps(dict(
    migrationID=migration, deviceID=device, installID=install, sourceEpoch=str(uuid.uuid4()),
    resources=resources, prefixBytes=prefix_size, remainingBytes=remaining_mib * 1024**2, totalBytes=small_bytes + large_size)))
print(json.dumps(dict(items=2889, verifiedResources=2888, pendingSize=large_size,
                      durablePrefix=prefix_size, remainingBytes=large_size-prefix_size,
                      totalBytes=small_bytes+large_size)))
